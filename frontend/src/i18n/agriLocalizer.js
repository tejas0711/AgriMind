// Localize positive and limiting factors
export function localizeFactor(text, lang) {
  if (!text || lang === "en") return text;

  // Patterns for positive factors
  if (text.includes("supports strong root establishment")) {
    return lang === "hi"
      ? text.replace(/Available phosphorus \(([\d.]+ \w+\/\w+)\) supports strong root establishment \(\+(\d+) pts\)\./i, "उपलब्ध फास्फोरस ($1) जड़ों के मजबूत विकास में सहायक है (+$2 अंक)।")
      : text.replace(/Available phosphorus \(([\d.]+ \w+\/\w+)\) supports strong root establishment \(\+(\d+) pts\)\./i, "उपलब्ध स्फुरद ($1) मुळांच्या मजबूत वाढीसाठी अत्यंत अनुकूल आहे (+$2 गुण).");
  }

  if (text.includes("full season suitability credited") || text.includes("No specific season constraint")) {
    return lang === "hi"
      ? "कोई विशिष्ट मौसमी बाधा नहीं; पूर्ण मौसमी अनुकूलता मान्य (+25 अंक)।"
      : "कोणतीही हंगामी अडचण नाही; पूर्ण हंगामी अनुकूलता ग्राह्य (+25 गुण).";
  }

  if (text.includes("is within optimal range") || text.includes("optimal range")) {
    return lang === "hi"
      ? text.replace(/Soil pH \(([\d.]+)\) is within optimal range \(([\d.-]+)\) \(\+(\d+) pts\)\./i, "मिट्टी का pH ($1) अनुकूल सीमा ($2) के भीतर है (+$3 अंक)।")
      : text.replace(/Soil pH \(([\d.]+)\) is within optimal range \(([\d.-]+)\) \(\+(\d+) pts\)\./i, "मातीचा pH ($1) पिकासाठी योग्य मर्यादेत ($2) आहे (+$3 गुण).");
  }

  if (text.includes("is adequate")) {
    return lang === "hi"
      ? text.replace(/Available (\w+) \(([\d.]+ \w+\/\w+)\) is adequate \(\+(\d+) pts\)\./i, "उपलब्ध $1 ($2) पर्याप्त स्तर पर है (+$3 अंक)।")
      : text.replace(/Available (\w+) \(([\d.]+ \w+\/\w+)\) is adequate \(\+(\d+) pts\)\./i, "उपलब्ध $1 ($2) पुरेसे आहे (+$3 गुण).");
  }

  // Patterns for limiting factors
  if (text.includes("is above target")) {
    return lang === "hi"
      ? text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is above target \(([\d.-]+ \w+\/\w+)\)\./i, "$1 स्तर ($2) अनुशंसित लक्ष्य ($3) से अधिक है।")
      : text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is above target \(([\d.-]+ \w+\/\w+)\)\./i, "$1 चे प्रमाण ($2) शिफारशीत मर्यादेपेक्षा ($3) जास्त आहे.");
  }

  if (text.includes("is below target") || text.includes("is below recommended")) {
    return lang === "hi"
      ? text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is below target \(([\d.-]+ \w+\/\w+)\)\./i, "$1 स्तर ($2) अनुशंसित लक्ष्य ($3) से कम है।")
      : text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is below target \(([\d.-]+ \w+\/\w+)\)\./i, "$1 चे प्रमाण ($2) शिफारशीपेक्षा ($3) कमी आहे.");
  }

  if (text.includes("is deficient") || text.includes("deficient")) {
    return lang === "hi"
      ? text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is deficient/i, "$1 स्तर ($2) कम (कमी) है")
      : text.replace(/(\w+) level \(([\d.]+ \w+\/\w+)\) is deficient/i, "$1 चे प्रमाण ($2) कमी आढळले आहे");
  }

  return text;
}

