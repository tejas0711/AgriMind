from __future__ import annotations

from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field

from app.models.soil import SoilReport
from app.models.crop import CropScore


class Deficiency(BaseModel):
    """Nutrient classification status and agronomic implication."""
    nutrient: str
    status: str              # "LOW" | "MEDIUM" | "HIGH" | "UNKNOWN"
    detail: str
    value: Optional[float] = None
    unit: Optional[str] = None
    threshold_used: Optional[str] = None
    rule_source: Optional[str] = None
    agronomic_implication: Optional[str] = None


class FertilizerOption(BaseModel):
    """Recommended fertilizer or soil amendment option with purpose and cautions."""
    name: str
    type: str                 # "chemical" | "organic"
    nutrient: str
    application_notes: str
    source: Optional[str] = None
    purpose: Optional[str] = None
    cautions: Optional[str] = None
    is_provisional: bool = True


class Evidence(BaseModel):
    text: str
    source: str
    score: float
    title: Optional[str] = None
    issuing_organization: Optional[str] = None
    doc_date: Optional[str] = None
    url_or_file: Optional[str] = None
    page_number: Optional[int] = None
    category: Optional[str] = None
    heading: Optional[str] = None


class ApplicationWindow(BaseModel):
    recommendation: str        # "YES" | "NO" | "CONDITIONAL"
    apply_today: str           # "GO" | "WAIT"
    reason: str
    next_window: Optional[str] = None
    forecast_summary: Optional[Dict[str, Any]] = None
    forecast_days: List[Dict[str, Any]] = Field(default_factory=list)
    location_name: Optional[str] = None
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    fetched_at: Optional[str] = None
    provider: str = "Open-Meteo"
    attribution: str = "Weather data by Open-Meteo.com (CC BY 4.0)"
    current_temperature_c: Optional[float] = None
    current_condition: Optional[str] = None
    limitations: Optional[str] = "Weather forecasts are probabilistic estimates subject to local micro-climate shifts. Always inspect field conditions and soil moisture before application."
    is_available: bool = True
    error: Optional[str] = None


class WhyThisRecommendation(BaseModel):
    reason_soil: str
    evidence: List[Evidence] = Field(default_factory=list)
    weather_factor: Optional[str] = None
    confidence: float = 0.0          # 0-1
    contradictions: List[str] = Field(default_factory=list)
    missing_warnings: List[str] = Field(default_factory=list)
    uncertainty_notes: Optional[str] = None
    provisional_notice: Optional[str] = None
    rule_sources: List[str] = Field(default_factory=list)


class RecommendationResponse(BaseModel):
    soil: SoilReport
    deficiencies: List[Deficiency]
    crop_scores: List[CropScore]
    fertilizer_options: List[FertilizerOption]
    application_window: Optional[ApplicationWindow] = None
    why: WhyThisRecommendation
    llm_explanation: Optional[str] = None
    llm_provider: Optional[str] = Field(default=None, description="LLM provider name or 'template_fallback'")
    llm_model: Optional[str] = Field(default=None, description="Model identifier if generated by an LLM")
    is_llm_fallback: bool = Field(default=False, description="True if generated by deterministic template fallback")
    language: str = "en"  # language the llm_explanation was generated in
    missing_warnings: List[str] = Field(default_factory=list)
    contradictions: List[str] = Field(default_factory=list)
    partial_failures: List[str] = Field(default_factory=list, description="Clear reporting of non-fatal service failures (e.g. weather unavailable)")
    location_name: Optional[str] = None
    provisional_disclaimer: str = Field(
        default=(
            "Nutrient evaluations and suitability rankings are derived from documented ICAR/Soil Health Card rules. "
            "Specific fertilizer dosages are provisional and require verification by local agricultural extension officers "
            "or Krishi Vigyan Kendra (KVK) based on targeted yield and field micro-conditions."
        ),
        description="Official cautionary notice on provisional recommendations"
    )
